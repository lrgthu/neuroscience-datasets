def record_to_dict(
    record: schema.DatasetRecord,
    card_markdown: str,
    bibtex_by_key: Mapping[str, str],
) -> dict[str, Any]:
    """Serializes a DatasetRecord with resolved Markdown and BibTeX snippets."""
    payload = dataclasses.asdict(record)
    all_keys = record.citations.primary_bib_keys + record.citations.related_bib_keys
    payload["card_markdown"] = card_markdown
    payload["resolved_bibtex"] = "\n\n".join(
        bibtex_by_key[key] for key in all_keys if key in bibtex_by_key
    )
    return payload


def render_datasets_json(catalog: loader.LoadedCatalog) -> str:
    """Renders deterministic JSON string for `catalog/datasets.json`."""
    items = [
        record_to_dict(
            rec,
            card_markdown=catalog.cards_by_id[rec.id],
            bibtex_by_key=catalog.bibtex_by_key,
        )
        for rec in catalog.records
    ]
    envelope = {
        "schema_version": "1.0.0",
        "dataset_count": len(items),
        "input_sha256": catalog.input_sha256,
        "datasets": items,
    }
    return json.dumps(envelope, indent=2, ensure_ascii=False) + "\n"


def render_pages_js(catalog: loader.LoadedCatalog) -> str:
    """Renders `docs/catalog_data.js` so static explorer works on Pages and file://."""
    json_body = render_datasets_json(catalog).strip()
    return (
        "// Auto-generated by scripts/build_catalog.py — DO NOT EDIT MANUALLY.\n"
        f"window.NEURO_CATALOG = {json_body};\n"
    )


def render_tidy_csv(records: Sequence[schema.DatasetRecord]) -> str:
    """Renders Tidy CSV (`1 row = 1 dataset`, pure atomic numbers, empty string NA)."""
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=CSV_COLUMNS, lineterminator="\n")
    writer.writeheader()
    for rec in records:
        writer.writerow(
            {
                "id": rec.id,
                "short_name": rec.short_name,
                "name": rec.name,
                "category": rec.category,
                "year": rec.year,
                "primary_species": rec.species[0],
                "all_species": ";".join(rec.species),
                "primary_modality": rec.modalities[0],
                "all_modalities": ";".join(rec.modalities),
                "domains": ";".join(rec.domains),
                "n_subjects": rec.scale.n_subjects,
                "hours_per_subject": (
                    ""
                    if rec.scale.hours_per_subject is None
                    else rec.scale.hours_per_subject
                ),
                "total_hours": (
                    "" if rec.scale.total_hours is None else rec.scale.total_hours
                ),
                "n_stimuli": (
                    "" if rec.scale.n_stimuli is None else rec.scale.n_stimuli
                ),
                "n_channels_or_voxels": rec.scale.n_channels_or_voxels,
                "sampling_rate_or_tr": rec.scale.sampling_rate_or_tr,
                "access_tier": rec.access.tier,
                "license": rec.access.license,
                "primary_portal": rec.access.primary_portal,
                "accession_ids": ";".join(rec.access.accession_ids),
                "data_formats": ";".join(rec.data_formats),
                "primary_doi_or_arxiv": rec.citations.primary_doi_or_arxiv,
                "primary_bib_key": rec.citations.primary_bib_keys[0],
                "homepage_url": rec.access.urls["homepage"],
                "card_path": rec.card_path,
                "last_verified": rec.last_verified,
            }
        )
    return buf.getvalue()


def _format_ref_link(doi_or_arxiv: str) -> str:
    if doi_or_arxiv.lower().startswith("arxiv:"):
        arxiv_id = doi_or_arxiv.split(":", 1)[1]
        return f"[`{doi_or_arxiv}`](https://arxiv.org/abs/{arxiv_id})"
    return f"[`{doi_or_arxiv}`](https://doi.org/{doi_or_arxiv})"


def render_markdown_catalog(records: Sequence[schema.DatasetRecord], lang: str) -> str:
    """Renders grouped Markdown summary tables for README.md or README_zh.md."""
    titles = CATEGORY_TITLES_ZH if lang == "zh" else CATEGORY_TITLES_EN
    ordered_cats = list(titles.keys())
    sections: list[str] = []
    for cat in ordered_cats:
        group = [r for r in records if r.category == cat]
        if not group:
            continue
        heading = f"### {titles[cat]} (`{len(group)}`)"
        if lang == "zh":
            header = (
                "| 数据集 | 年份 | 物种 / 模态 | 被试数 ($N$) & 规模 | 开放级别 / 入口 | 深度卡片 & 文献 |\n"
                "| :--- | :---: | :--- | :--- | :--- | :--- |"
            )
        else:
            header = (
                "| Dataset | Year | Species / Modalities | Subjects ($N$) & Scale | Access / Portal | Card & Primary Ref |\n"
                "| :--- | :---: | :--- | :--- | :--- | :--- |"
            )
        rows: list[str] = []
        for rec in sorted(group, key=lambda item: (-item.year, item.short_name)):
            mods = ", ".join(f"`{m}`" for m in rec.modalities[:3])
            species_str = "/".join(rec.species)
            hrs = (
                f", ~{rec.scale.hours_per_subject:g} h/subj"
                if rec.scale.hours_per_subject is not None
                else ""
            )
            stims = (
                f", {rec.scale.n_stimuli:,} stim"
                if rec.scale.n_stimuli is not None
                else ""
            )
            scale_cell = f"`N={rec.scale.n_subjects}`{hrs}{stims}"
            acc = (
                f" ({rec.access.accession_ids[0]})"
                if rec.access.accession_ids
                else ""
            )
            portal_cell = (
                f"`{rec.access.tier}` · [{rec.access.primary_portal}]"
                f"({rec.access.urls['homepage']}){acc}"
            )
            card_label = "卡片" if lang == "zh" else "Card"
            ref_cell = (
                f"[{card_label}](./{rec.card_path}) · "
                f"{_format_ref_link(rec.citations.primary_doi_or_arxiv)}"
            )
            rows.append(
                f"| **{rec.short_name}**<br><sub>{rec.name}</sub> | {rec.year} | "
                f"{species_str}<br>{mods} | {scale_cell} | {portal_cell} | {ref_cell} |"
            )
        sections.append("\n".join([heading, "", header, *rows]))
    return "\n\n".join(sections)


def splice_readme_block(readme_text: str, generated_table: str) -> str:
    """Replaces text between CATALOG markers in a README document."""
    start_idx = readme_text.find(README_START_MARKER)
    end_idx = readme_text.find(README_END_MARKER)
    if start_idx == -1 or end_idx == -1 or end_idx < start_idx:
        raise ValueError(
            f"README is missing {README_START_MARKER} ... {README_END_MARKER} markers"
        )
    prefix = readme_text[: start_idx + len(README_START_MARKER)]
    suffix = readme_text[end_idx:]
    return f"{prefix}\n\n{generated_table}\n\n{suffix}"


def _git_metadata(repo_root: pathlib.Path) -> tuple[str, bool]:
    try:
        sha = (
            subprocess.check_output(
                ["git", "rev-parse", "HEAD"],
                cwd=repo_root,
                stderr=subprocess.DEVNULL,
            )
            .decode("utf-8")
            .strip()
        )
        dirty_out = (
            subprocess.check_output(
                ["git", "status", "--porcelain"],
                cwd=repo_root,
                stderr=subprocess.DEVNULL,
            )
            .decode("utf-8")
            .strip()
        )
        return sha, bool(dirty_out)
    except (OSError, subprocess.CalledProcessError):
        return "uncommitted", True


def build_provenance_dict(
    catalog: loader.LoadedCatalog, repo_root: pathlib.Path
) -> dict[str, Any]:
    """Constructs machine-readable provenance metadata for generated catalog files."""
    sha, is_dirty = _git_metadata(repo_root)
    return {
        "schema_version": "1.0.0",
        "generated_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "git_commit_sha": sha,
        "git_is_dirty": is_dirty,
        "python_version": platform.python_version(),
        "dataset_count": len(catalog.records),
        "verified_bibtex_key_count": len(catalog.bibtex_by_key),
        "input_sha256": catalog.input_sha256,
    }
